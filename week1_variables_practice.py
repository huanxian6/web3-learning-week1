# --- 1. 变量就是"名字贴纸"，贴在数据上 ---
name = "小明"          # 把字符串"小明"起名叫 name
age = 18               # 把整数 18 起名叫 age
height = 1.75          # 把小数 1.75 起名叫 height
is_student = True      # 把布尔值 True 起名叫 is_student

# --- 2. print() 输出变量的值 ---
print(name)
print(age)

# --- 3. type() 看数据类型（初学阶段一定要多用！）---
print(type(name))        # <class 'str'>    字符串
print(type(age))         # <class 'int'>    整数p
print(type(height))      # <class 'float'>  小数
print(type(is_student))  # <class 'bool'>   布尔值

# --- 4. f-string：把变量嵌进一句话里（最推荐）---
print(f"我叫{name}，今年{age}岁，身高{height}米")

# --- 5. 老写法：字符串拼接（数字必须先用 str() 转成字符串）---
print("我叫" + name + "，今年" + str(age) + "岁")

# --- 6. input() 接收用户输入 ---
# ⚠️ 关键坑：input() 拿到的永远是字符串 str！
# user_age = input("请输入你的年龄：")
# print(type(user_age))        # <class 'str'>  ← 注意不是 int
# print(int(user_age) + 1)     # 想算数，必须先 int() 转换

# --- 7. 类型转换三兄弟 ---
print(int("100") + 1)     # 101  字符串 → 整数
print(float("3.14") * 2)  # 6.28 字符串 → 小数
print(str(666) + "abc")   # 666abc  数字 → 字符串


